#ifndef IOTHUBCOMMS_INBOUNDMESSAGEINTERFACE_HPP
#define IOTHUBCOMMS_INBOUNDMESSAGEINTERFACE_HPP

#include <cstdint>
#include <vector>

#include <boost/serialization/version.hpp>
#include <boost/serialization/vector.hpp>

#include <ais/serialization/Datum.h>
#include <ais/serialization/csvable.h>


/*
 * The interface storage class.
 */
class IoTHubCommsInboundMessageInterfaceStorage : public csvable {
public:
    IoTHubCommsInboundMessageInterfaceStorage() = default;

    uint32_t fileType;
    std::vector<uint8_t> messageContents;
    std::string messageId; // Mobile Terminated GUID from back office
    std::string correlationId; // (optional) Mobile Terminated GUID generated by web app in response to setting IOTHubMessageTransmit.GenerateMessageIDGUID
                               // (optional) If populated should match the GUID from IOTHubMessageReturn.MessageID

    void toCsv(CsvOutStream& out) const {
        // Not supported.
    }

    template<class Archive>
    void serialize(Archive& ar, const unsigned int version) {
        ar & fileType;
        ar & messageContents;
        ar & messageId;
        ar & correlationId;
    }
};

/*
 * Datum template specialization.
 *   Defines a new specialization of the Datum class
 *   derived from the base 'storage' class.
 */
typedef Datum<IoTHubCommsInboundMessageInterfaceStorage> IoTHubCommsInboundMessageInterface;

BOOST_CLASS_VERSION(IoTHubCommsInboundMessageInterfaceStorage, 1);

#endif
