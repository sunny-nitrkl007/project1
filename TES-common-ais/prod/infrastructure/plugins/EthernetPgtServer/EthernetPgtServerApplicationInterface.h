#ifndef ETHERNETPGTSERVERAPPLICATIONINTERFACE_H_
#define ETHERNETPGTSERVERAPPLICATIONINTERFACE_H_

class EthernetPgtServerApplicationInterface
{
public:
    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Set the PID value
    /// @return true if successful, false
    ///////////////////////////////////////////////////////////////////////////////
    virtual bool setPidValueEng(uint32_t paramId, double value) = 0;

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Set the raw PID/unscaled value.  Useful for gear PIDs etc.
    /// @return true if successful, false
    ///////////////////////////////////////////////////////////////////////////////
    virtual bool setPidValueRaw(uint32_t paramId, uint32_t value) = 0;

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Set the DSI of the PID, if > 0 the value is overwritten
    /// @return true if successful, false
    ///////////////////////////////////////////////////////////////////////////////
    virtual bool setPidDsi(uint32_t paramId, uint8_t dsi)
    { 
        AIS_LOG_ERROR("setPidDsi not implemented");
        return false;
    }

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Set the SPN value
    /// @return true if successful, false
    ///////////////////////////////////////////////////////////////////////////////
    virtual bool setSpnValueEng(uint32_t spnId, double value) = 0;

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Set the CAT Ext Id value
    /// @return true if successful, false
    ///////////////////////////////////////////////////////////////////////////////
    virtual bool setCatExtIdValue(uint32_t catExtId, uint32_t value) = 0;
};

#endif
