///////////////////////////////////////////////////////////////////////////////
// -- Class Definitions
///////////////////////////////////////////////////////////////////////////////

// Interface to DataLinkData
class DataLinkDataTxProvider
{
public:
    /// Constructor
    DataLinkDataTxProvider() : newData(false) {}
    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Get the DataLinkData object
    /// @return reference to the DataLinkData
    ///////////////////////////////////////////////////////////////////////////////
    virtual DataLinkData& getTxObject() { return m_DataLinkData; }

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Notify DataLinkDataTxProvider that there is new data to send
    ///////////////////////////////////////////////////////////////////////////////
    virtual void sendData() { newData = true; }

protected:
    bool newData;
    DataLinkData m_DataLinkData;
};

// Packages all received DataLinkData objects into a DataLinkDataRxContainer.
// Intended to be run sequentially with other plugins, i.e. access to DataLinkPackage
// is not thread safe
class DataLinkDataPublisher : public TaskPlugin, public DataLinkDataTxProvider
{
public:

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Constructor request a reference to the parent task
    ///////////////////////////////////////////////////////////////////////////////
    DataLinkDataPublisher() = delete;
    DataLinkDataPublisher() :
        m_pDataLinkDataOutput(nullptr)
    {};

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Get the plugin name (used for configuring update rate)
    /// @return name of the plugin
    ///////////////////////////////////////////////////////////////////////////////
    std::string getName() override { return "DataLinkDataPublisher"; }

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Initializes the plugin.
    /// @return true if successful, otherwise false
    ///////////////////////////////////////////////////////////////////////////////
    bool initialize() override
    {
        if (!task::InterfaceDb::bind("DataLinkDataPublisherOutput", m_pDataLinkDataOutput))
        {
            return false;
        }

        return true;
    }

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Updates the plugin, expected to be called every executive loop of the
    ///        parent task.
    /// @return true if successful, otherwise false
    ///////////////////////////////////////////////////////////////////////////////
    bool update() override
    {
        if (newData)
        {
            m_pDataLinkDataOutput->publish(m_DataLinkData);
            newData = false;
        }
        return true;
    }

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Called during cleanup of the parent task.
    ///////////////////////////////////////////////////////////////////////////////
    void cleanup() override {};

protected:
private:
    DataLinkDataOutput* m_pDataLinkDataOutput;
};

#endif
