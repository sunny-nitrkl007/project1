#ifndef DataLinkBridgeApplicationInterface_H_
#define DataLinkBridgeApplicationInterface_H_

class DataLinkBridgeApplicationInterface
{
public:
    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Set the PID tx value
    /// @return true if successful, false otherwise
    ///////////////////////////////////////////////////////////////////////////////
    virtual bool SetParamTxValue(uint32_t paramId, uint16_t value) = 0;

    ///////////////////////////////////////////////////////////////////////////////
    /// @brief Get the PID rx value
    /// @return true if parameter was received, false otherwise
    ///////////////////////////////////////////////////////////////////////////////
    virtual bool GetParamRxValue(uint32_t paramId, uint16_t& value) = 0;
};

#endif
