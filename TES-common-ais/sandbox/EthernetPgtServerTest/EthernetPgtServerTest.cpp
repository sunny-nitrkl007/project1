///////////////////////////////////////////////////////////////////////////////
/// @brief EthernetPgtServerTest Initialize
///
/// @return
///
///////////////////////////////////////////////////////////////////////////////
bool EthernetPgtServerTest::initialize()
{
    // Initialize plugins before J1939 communication stack initialization
    if (!initializePlugins())
    {
        return false;
    }

    // Initialize communication stack. Call this at the end of autonomyInitialize()
    // so that communication stack can accept config parameteres from ruby file
    commInitialize();

    while (FALSE == app_init_completed)
    {
        sleep(1);
    }

    // Initialize any plugins that require J1939 communication stack initialization
    if (!postInitializePlugins())
    {
        return false;
    }

    m_initDone = true;
    return true;
}

///////////////////////////////////////////////////////////////////////////////
/// @brief Main loop for EthernetPgtServerTest.
///
/// @return true/false
///
///////////////////////////////////////////////////////////////////////////////
bool EthernetPgtServerTest::executive()
{
    if (!m_initDone)
    {
        return true;
    }

    // Update Plugins
    if (!updatePlugins())
    {
        return false;
    }

    return true;
}

///////////////////////////////////////////////////////////////////////////////
/// @brief Cleanup for the EthernetPgtServerTest
///////////////////////////////////////////////////////////////////////////////
void EthernetPgtServerTest::cleanup()
{
    cleanupPlugins();
}
